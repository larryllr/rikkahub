import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { presentationGrammar } from './web-presentation.mjs';

const android = new URL('../../app/src/main/', import.meta.url);
await build({
  entryPoints: [fileURLToPath(new URL('entry.mjs', import.meta.url))],
  bundle: true,
  format: 'iife',
  globalName: 'KuanPresentation',
  target: 'es2023',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  minify: true,
  legalComments: 'inline',
  outfile: fileURLToPath(new URL('assets/kuan-presentation.js', android)),
});

const kotlin = Object.entries(presentationGrammar).map(([key, pattern]) => {
  const name = 'kuanPresentation' + key[0].toUpperCase() + key.slice(1);
  const option = key === 'code' ? 'MULTILINE' : 'IGNORE_CASE';
  return `internal val ${name} = Regex(\n    """${pattern}""",\n    RegexOption.${option},\n)`;
});
await writeFile(new URL('java/me/rerere/rikkahub/data/kuan/KuanPresentationGrammar.kt', android),
  '// Generated by tools/kuan-presentation/build.mjs from the projection grammar.\n'
  + 'package me.rerere.rikkahub.data.kuan\n\n' + kotlin.join('\n\n') + '\n');
